    public HoroscopeCard Get(string sign, DateOnly date)
    {
        var key = Encoding.UTF8.GetBytes($"{sign}|{date:yyyy-MM-dd}");
        var hash = SHA256.HashData(key);
        var theme = Themes[hash[0] % Themes.Length];
        var opening = theme.Openings[hash[1] % theme.Openings.Length];
        var closing = theme.Closings[hash[2] % theme.Closings.Length];
        return new(sign, $"{opening} {closing}", "Развлекательный прогноз, не основанный на научном методе.", theme.Key, theme.Title);
    }
}
