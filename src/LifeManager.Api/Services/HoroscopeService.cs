using System.Security.Cryptography;
using System.Text;
using LifeManager.Api.Domain;

namespace LifeManager.Api.Services;

public sealed class HoroscopeService
{
    private static readonly string[] Openings =
    [
        "Сегодня лучше не распыляться: один завершённый вопрос даст больше спокойствия, чем пять начатых.",
        "День подходит для наведения порядка в мелочах, которые давно висят фоном.",
        "Сегодня полезно оставить в расписании немного воздуха и не забивать день до отказа.",
        "Хороший день, чтобы вернуться к делу, которое несколько раз откладывалось.",
        "Сегодня стоит выбирать решения, после которых завтра станет проще, а не только приятнее прямо сейчас."
    ];

    private static readonly string[] Closings =
    [
        "Для настроения: маленькая приятная покупка или прогулка может хорошо переключить голову.",
        "Для настроения: не игнорируй желание сделать пространство вокруг себя уютнее.",
        "Для настроения: вечером лучше выбрать спокойный сценарий и не перегружать себя планами.",
        "Для настроения: день хорошо подходит для общения с теми, рядом с кем не нужно напрягаться.",
        "Для настроения: сегодня особенно приятно будет закрыть один старый бытовой хвост."
    ];

    public HoroscopeCard Get(string sign, DateOnly date)
    {
        var key = Encoding.UTF8.GetBytes($"{sign}|{date:yyyy-MM-dd}");
        var hash = SHA256.HashData(key);
        var text = $"{Openings[hash[0] % Openings.Length]} {Closings[hash[1] % Closings.Length]}";
        return new(sign, text, "Развлекательный прогноз, не основанный на научном методе.");
    }
}
