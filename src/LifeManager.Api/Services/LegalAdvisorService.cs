            steps.Add("Направь оператору или владельцу ресурса письменное требование по ситуации и сохрани подтверждение обращения.");
            steps.Add("Если вопрос не решён, проверь порядок обращения в Роскомнадзор и нормы 152-ФЗ по ссылкам ниже.");
        }
        else
        {
            steps.Add("Составь короткую хронологию: что произошло, кто вторая сторона, какие даты и суммы важны.");
            steps.Add("Собери документы и цифровые подтверждения: договоры, чеки, письма, сообщения, уведомления и скриншоты.");
