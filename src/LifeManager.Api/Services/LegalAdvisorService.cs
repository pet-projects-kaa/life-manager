    public LegalAdvice Get(string category, string text)
    {
        var clean = Regex.Replace(text ?? string.Empty, "\\s+", " ").Trim();
        if (clean.Length < 8)
            return new("general", "Нужно чуть больше деталей", "Опиши, что произошло, кто вторая сторона, когда это случилось и чего ты хочешь добиться.",
                ["Добавь даты и суммы, если они есть.", "Укажи, есть ли договор, чек, переписка или другое подтверждение.", "Напиши желаемый результат: возврат денег, отмена списания, ремонт, выплата, исправление документа и т.п."],
                [], Disclaimer());

        var area = PickArea(category, clean);
        var facts = ExtractFacts(clean);
        var steps = BuildSteps(area.Key, clean, facts);
        var summary = BuildSummary(area, clean, facts);
        var title = BuildTitle(area.Key, clean);

        return new(area.Key, title, summary, steps, area.Sources, Disclaimer());
    }

    private static Area PickArea(string category, string text)
    {
        var normalized = $"{category} {text}".ToLowerInvariant();
        return Areas
            .Select(a => new { Area = a, Score = (a.Key == category ? 3 : 0) + a.Keywords.Count(k => normalized.Contains(k, StringComparison.OrdinalIgnoreCase)) })
            .OrderByDescending(x => x.Score)
            .ThenBy(x => x.Area.Key)
            .FirstOrDefault(x => x.Score > 0)?.Area
            ?? GeneralArea;
    }

    private static string BuildTitle(string key, string text)
    {
        var n = text.ToLowerInvariant();
        if (key == "consumer" && (n.Contains("достав") || n.Contains("заказ"))) return "Задержка или проблема с доставкой";
        if (key == "consumer" && (n.Contains("брак") || n.Contains("некаче") || n.Contains("слом"))) return "Проблема с качеством товара";
        if (key == "consumer" && (n.Contains("возврат") || n.Contains("вернуть"))) return "Возврат товара или денег";
        if (key == "work" && n.Contains("уволь")) return "Вопрос по увольнению";
        if (key == "work" && n.Contains("зарплат")) return "Вопрос по зарплате";
        if (key == "housing" && (n.Contains("аренд") || n.Contains("залог"))) return "Спор по аренде жилья";
        if (key == "bank" && n.Contains("списан")) return "Спорное списание";
        if (key == "tax" && n.Contains("вычет")) return "Проверка права на налоговый вычет";
        return key == "general" ? GeneralArea.Title : Areas.First(x => x.Key == key).Title;
    }

    private static string BuildSummary(Area area, string text, Facts facts)
    {
        var pieces = new List<string> { $"По описанию это похоже на ситуацию из категории «{area.Title}»." };
        if (facts.Amount is not null) pieces.Add($"В тексте фигурирует сумма около {facts.Amount}." );
        if (facts.HasDeadline) pieces.Add("Есть указание на срок или просрочку — дату лучше зафиксировать отдельно.");
        if (facts.HasWrittenEvidence) pieces.Add("У тебя, судя по описанию, могут быть письменные подтверждения — это полезно для претензии или обращения.");
        pieces.Add("Ниже — практический порядок действий; перед отправкой официального требования открой приложенные источники и сверь актуальную редакцию нормы с твоими обстоятельствами.");
        return string.Join(" ", pieces);
    }

