    public LegalAdvice Get(string category, string text)
    {
        var clean = Compact(text);
        if (clean.Length < 12)
            return NeedMoreDetails();

        var normalized = Normalize(clean);
        var tokens = Tokenize(normalized);
        var ranked = Scenarios
            .Select(s => Score(s, category, normalized, tokens))
            .OrderByDescending(x => x.Score)
            .ThenByDescending(x => x.PhraseHits.Count)
            .ToArray();

        var best = ranked[0];
        var second = ranked.Length > 1 ? ranked[1] : null;
        var margin = second is null ? best.Score : best.Score - second.Score;

        if (best.Score < 2.4)
            return GeneralAdvice(clean);

        var facts = ExtractFacts(clean);
        var confidence = Confidence(best.Score, margin, best.PhraseHits.Count);
        var ambiguous = margin < 1.2 && best.Score < 7;
        var followUps = BuildFollowUps(best.Scenario, facts, ambiguous ? second?.Scenario : null);
        var steps = BuildSteps(best.Scenario.Key, normalized, facts);
        var summary = BuildSummary(best.Scenario, facts, confidence, ambiguous ? second?.Scenario : null);
        var signals = best.PhraseHits.Concat(best.RootHits).Distinct(StringComparer.OrdinalIgnoreCase).Take(7).ToArray();

        IEnumerable<LegalSource> sourceQuery = best.Scenario.Sources;
        if (ambiguous && second is not null)
            sourceQuery = sourceQuery.Concat(second.Scenario.Sources.Take(1));
        var sources = sourceQuery.DistinctBy(x => x.Url).Take(5).ToArray();

        return new(best.Scenario.Area, best.Scenario.Title, summary, steps, sources, Disclaimer(), confidence, signals, followUps);
    }

    private sealed record ScoredScenario(Scenario Scenario, double Score, IReadOnlyList<string> PhraseHits, IReadOnlyList<string> RootHits);

    private static ScoredScenario Score(Scenario scenario, string category, string normalized, HashSet<string> tokens)
    {
        var phrases = scenario.Phrases.Where(x => normalized.Contains(x, StringComparison.OrdinalIgnoreCase)).Distinct(StringComparer.OrdinalIgnoreCase).ToArray();
        var roots = scenario.Roots.Where(root => tokens.Any(t => t.StartsWith(root, StringComparison.OrdinalIgnoreCase))).Distinct(StringComparer.OrdinalIgnoreCase).ToArray();
        var score = phrases.Length * 5.5 + roots.Length * 1.15;

        if (!string.IsNullOrWhiteSpace(category) && !string.Equals(category, "auto", StringComparison.OrdinalIgnoreCase) &&
            string.Equals(category, scenario.Area, StringComparison.OrdinalIgnoreCase))
            score += 1.5; // manual category is only a hint, never enough to override the text

        // Strong cross-area signals reduce common false positives.
        if (scenario.Area == "consumer" && (tokens.Contains("работодатель") || tokens.Any(x => x.StartsWith("зарплат")))) score -= 4;
        if (scenario.Area == "work" && (tokens.Contains("продавец") || tokens.Any(x => x.StartsWith("маркетплейс")))) score -= 3;
        if (scenario.Area == "bank" && tokens.Any(x => x.StartsWith("аренд"))) score -= 3;
        return new ScoredScenario(scenario, score, phrases, roots);
    }

    private static int Confidence(double score, double margin, int phraseHits)
    {
        var value = 38 + Math.Min(38, score * 4) + Math.Min(14, Math.Max(0, margin) * 4) + Math.Min(8, phraseHits * 4);
        return (int)Math.Clamp(Math.Round(value), 42, 98);
    }

    private static string BuildSummary(Scenario scenario, Facts facts, int confidence, Scenario? alternative)
    {
        var parts = new List<string> { $"По тексту наиболее вероятный сценарий — «{scenario.Title}» (уверенность классификации {confidence}%)." };
        if (alternative is not null) parts.Add($"Есть пересечение с темой «{alternative.Title}», поэтому ниже оставлены уточняющие вопросы.");
        if (facts.Amount is not null) parts.Add($"Распознана сумма: {facts.Amount}.");
        if (facts.HasDeadline) parts.Add("В описании есть срок/просрочка — точная дата может существенно менять порядок действий.");
        if (facts.HasWrittenEvidence) parts.Add("Похоже, есть письменные подтверждения; их стоит сохранить в исходном виде.");
