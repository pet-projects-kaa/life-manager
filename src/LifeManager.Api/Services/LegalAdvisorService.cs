    [GeneratedRegex(@"(\d[\d\s]*(?:[.,]\d{1,2})?)\s*(?:₽|руб(?:\.|лей|ля)?|р\.)", RegexOptions.IgnoreCase)]
    private static partial Regex MoneyRegex();

