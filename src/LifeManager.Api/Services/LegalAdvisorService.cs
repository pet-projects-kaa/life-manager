    private static Facts ExtractFacts(string text)
    {
        var amountMatch = MoneyRegex().Match(text);
        var amount = amountMatch.Success ? Regex.Replace(amountMatch.Groups[1].Value, "\\s+", " ").Trim() + " ₽" : null;
        var n = Normalize(text);
        var hasDeadline = n.Contains("срок") || n.Contains("до ") || n.Contains("дней") || n.Contains("недел") || n.Contains("месяц") || DateRegex().IsMatch(text);
        var written = n.Contains("чек") || n.Contains("договор") || n.Contains("переписк") || n.Contains("скрин") || n.Contains("письм") || n.Contains("заказ") || n.Contains("уведомлен") || n.Contains("акт");
        return new Facts(amount, hasDeadline, written);
    }

    private sealed record Facts(string? Amount, bool HasDeadline, bool HasWrittenEvidence);

    private static HashSet<string> Tokenize(string normalized)
        => WordRegex().Matches(normalized).Select(x => x.Value).ToHashSet(StringComparer.OrdinalIgnoreCase);

    private static string Compact(string? text) => Regex.Replace(text ?? string.Empty, @"\s+", " ").Trim();
    private static string Normalize(string text) => Compact(text).ToLowerInvariant().Replace('ё', 'е');
    private static string Disclaimer() => "Справочная информация, а не персональная юридическая консультация. Классификация делается по тексту автоматически, право и практика меняются: перед значимым действием открой приложенные источники, проверь актуальную редакцию и соотнеси её со своими документами.";

    [GeneratedRegex(@"[\p{L}\p{N}-]+", RegexOptions.CultureInvariant)]
