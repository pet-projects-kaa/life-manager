            steps.Add("По ключевым словам из ситуации найди профильный нормативный акт в КонсультантПлюс; если вопрос связан с госуслугой, проверь официальный порядок на Госуслугах.");
        }

        if (facts.HasDeadline && !steps.Any(s => s.Contains("дат", StringComparison.OrdinalIgnoreCase)))
            steps.Insert(0, "Отдельно выпиши все даты: когда возникло обязательство, когда должен был наступить результат и когда ты обращалась к другой стороне.");
        return steps.Take(5).ToArray();
    }

    private static Facts ExtractFacts(string text)
    {
        var amountMatch = MoneyRegex().Match(text);
        var amount = amountMatch.Success ? Regex.Replace(amountMatch.Groups[1].Value, "\\s+", " ").Trim() + " ₽" : null;
        var n = text.ToLowerInvariant();
        var hasDeadline = n.Contains("срок") || n.Contains("до ") || n.Contains("числ") || n.Contains("дней") || n.Contains("недел") || n.Contains("месяц") || DateRegex().IsMatch(text);
        var written = n.Contains("чек") || n.Contains("договор") || n.Contains("переписк") || n.Contains("скрин") || n.Contains("письм") || n.Contains("заказ");
        return new Facts(amount, hasDeadline, written);
    }

    private sealed record Facts(string? Amount, bool HasDeadline, bool HasWrittenEvidence);

    private static string Disclaimer() => "Справочная информация, а не персональная юридическая консультация. Право меняется, а результат зависит от документов и фактов: перед значимым действием открой источники и проверь актуальную редакцию норм.";

    [GeneratedRegex(@"(\d[\d\s]*(?:[.,]\d{1,2})?)\s*(?:₽|руб(?:\.|лей|ля)?|р\.)", RegexOptions.IgnoreCase)]
    private static partial Regex MoneyRegex();

    [GeneratedRegex(@"\b(?:0?[1-9]|[12]\d|3[01])[./-](?:0?[1-9]|1[0-2])(?:[./-]\d{2,4})?\b")]
    private static partial Regex DateRegex();
