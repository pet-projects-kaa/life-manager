                else
                    steps.Add("Если всё ещё хочешь получить заказ, запроси новую конкретную дату исполнения, а не формулировку «скоро».");
            }
            else if (n.Contains("брак") || n.Contains("некаче") || n.Contains("слом"))
            {
                steps.Add("Сними фото или видео недостатка и сохрани чек, заказ, серийный номер и гарантийные документы, если они есть.");
                steps.Add("Определи одно конкретное требование к продавцу: возврат денег, замена, ремонт или уменьшение цены — не перечисляй все варианты одновременно.");
                steps.Add("Передавай товар на проверку качества или ремонт только с документом, где зафиксированы комплектность, внешний вид и заявленный недостаток.");
            }
            else
            {
                steps.Add("Собери чек или иное подтверждение покупки, условия заказа, переписку и фото/видео, если спор связан с качеством.");
                steps.Add("Письменно сформулируй продавцу или исполнителю одно конкретное требование и сохрани доказательство отправки.");
                steps.Add("Сверь свою ситуацию с актуальной редакцией Закона о защите прав потребителей по ссылке ниже.");
            }
            steps.Add("Если добровольно вопрос не решён, подготовь обращение в Роспотребнадзор или претензию для дальнейшего спора, приложив хронологию и подтверждения.");
        }
