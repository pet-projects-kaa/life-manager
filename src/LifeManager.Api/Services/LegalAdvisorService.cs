    private static IReadOnlyList<string> BuildFollowUps(Scenario scenario, Facts facts, Scenario? alternative)
    {
        var result = scenario.FollowUps.ToList();
        if (!facts.HasDeadline) result.Insert(0, "Какие точные даты или сроки здесь важны?");
        if (!facts.HasWrittenEvidence) result.Add("Какие документы или переписка подтверждают ситуацию?");
        if (alternative is not null) result.Add($"Уточни, относится ли спор скорее к теме «{scenario.AreaTitle}» или «{alternative.AreaTitle}».");
        return result.Distinct().Take(4).ToArray();
    }

